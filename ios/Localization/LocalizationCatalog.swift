extension LocalizationCatalog {
    static var currentLanguage: AppLanguage {
        if let rawLanguage = UserDefaults.standard.string(forKey: "app_language"),
           let storedLanguage = AppLanguage(rawValue: rawLanguage),
           AppLanguageRegistry.enabledInUI.contains(storedLanguage) {
            return storedLanguage
        }

        if let preferredLanguage = Locale.preferredLanguages.first,
           preferredLanguage.lowercased().hasPrefix("ru") {
            return .russian
        }

        return AppLanguage.fallback
    }

    static var currentLocale: Locale {
        Locale(identifier: currentLanguage.localeIdentifier)
    }

    static func text(_ key: LocalizationKey) -> String {
        if let value = catalog[currentLanguage]?[key] {
            return value
        }

        if let fallback = catalog[AppLanguage.fallback]?[key] {
            return fallback
        }

        return key.rawValue
    }
}
